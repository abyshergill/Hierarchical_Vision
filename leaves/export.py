"""CSV export of one employee's leave information."""
import csv
import re
from decimal import Decimal

from django.http import HttpResponse
from django.utils import timezone

from . import services
from .models import LeaveApplication

_FORMULA_START = ("=", "+", "-", "@", "\t", "\r")


def safe_cell(value):
    """Neutralise spreadsheet formula injection (employee-entered text such as reasons)."""
    if value is None:
        return ""
    if isinstance(value, Decimal):
        return str(value)
    text = str(value).replace("\r\n", "\n").replace("\r", "\n")
    return "'" + text if text.startswith(_FORMULA_START) else text


def safe_filename_part(value):
    return re.sub(r"[^A-Za-z0-9_-]", "_", str(value))[:40] or "employee"


def build_leave_csv_response(target, year, exported_by):
    balances = services.get_balances_for_users([target], year)[target.pk]
    applications = (
        LeaveApplication.objects.filter(applicant=target, start_date__year=year)
        .select_related("leave_type", "reviewed_by").prefetch_related("days").order_by("start_date", "created_at")
    )
    now = timezone.localtime()
    filename = f"leaves_{safe_filename_part(target.employee_id)}_{year}.csv"
    response = HttpResponse(content_type="text/csv; charset=utf-8")
    response["Content-Disposition"] = f'attachment; filename="{filename}"'
    response["Cache-Control"] = "private, no-store"
    response["X-Content-Type-Options"] = "nosniff"
    response.write("\ufeff")                      # BOM so Excel detects UTF-8
    w = csv.writer(response)

    w.writerow(["Employee leave report"])
    w.writerow(["Employee ID", safe_cell(target.employee_id)])
    w.writerow(["Name", safe_cell(target.full_name)])
    w.writerow(["Position", safe_cell(target.position)])
    w.writerow(["Email", safe_cell(target.email)])
    w.writerow(["Manager", safe_cell(target.manager.full_name if target.manager else "")])
    w.writerow(["Year", year])
    w.writerow(["Generated", now.strftime("%Y-%m-%d %H:%M")])
    w.writerow(["Generated by", safe_cell(f"{exported_by.full_name} ({exported_by.employee_id})")])
    w.writerow([])

    w.writerow(["LEAVE BALANCES"])
    w.writerow(["Leave type", "Code", "Allocated (days)", "Used (days)", "Pending (days)", "Remaining (days)",
                "Allocated (hours)", "Used (hours)", "Pending (hours)", "Remaining (hours)"])
    for b in balances:
        lt = b["leave_type"]
        w.writerow([safe_cell(lt.name), safe_cell(lt.code),
                    b["allocated_days"], b["used_days"], b["pending_days"], b["remaining_days"],
                    b["allocated_hours"], b["used_hours"], b["pending_hours"], b["remaining_hours"]])
    w.writerow([])

    w.writerow(["LEAVE APPLICATIONS"])
    w.writerow(["Leave type", "Start date", "End date", "Start time", "End time", "Hourly", "Hours", "Days",
                "Status", "Reason", "Applied on", "Reviewed by", "Reviewed at", "Review comment"])
    for a in applications:
        w.writerow([
            safe_cell(a.leave_type.name), a.start_date.isoformat(), a.end_date.isoformat(),
            a.start_time.strftime("%H:%M") if a.start_time else "",
            a.end_time.strftime("%H:%M") if a.end_time else "",
            "Yes" if a.is_hourly else "No", a.total_hours, a.total_days,
            a.get_status_display(), safe_cell(a.reason),
            timezone.localtime(a.created_at).strftime("%Y-%m-%d %H:%M"),
            safe_cell(a.reviewed_by.full_name if a.reviewed_by else ""),
            timezone.localtime(a.reviewed_at).strftime("%Y-%m-%d %H:%M") if a.reviewed_at else "",
            safe_cell(a.review_comment),
        ])
    w.writerow([])
    w.writerow(["LEAVE DAYS (time booked on each day)"])
    w.writerow(["Date", "Weekday", "Leave type", "From", "To", "Hours", "Status"])
    for a in applications:
        for d in a.days.all():
            w.writerow([d.date.isoformat(), d.date.strftime("%A"), safe_cell(a.leave_type.name),
                        d.start_time.strftime("%H:%M"), d.end_time.strftime("%H:%M"), d.hours, a.get_status_display()])
    return response
